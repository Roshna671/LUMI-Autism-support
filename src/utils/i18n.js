/**
 * Translate a key into the active language with optional parameter interpolation
 * @param {string} key - The dictionary key
 * @param {object} [params] - Dynamic parameter interpolation, e.g. { name: 'Aarav' }
 * @param {string} [lang] - Language code ('en', 'kn', 'hi', 'ta', 'te', 'ml'). Defaults to stored profile language.
 * @returns {string} Translated text
 */
export const t = (key, params = {}, lang = null) => {
  let activeLang = lang;
  if (!activeLang) {
    try {
      const savedProfile = localStorage.getItem('lumi_profile');
      if (savedProfile) {
        activeLang = JSON.parse(savedProfile).language;
      }
    } catch (e) {}
  }
  activeLang = activeLang || 'en';

  const dict = TRANSLATIONS[activeLang] || TRANSLATIONS['en'];
  let text = dict[key] || TRANSLATIONS['en'][key] || key;

  if (params && typeof params === 'object') {
    Object.keys(params).forEach((p) => {
      text = text.replace(new RegExp(`\\{${p}\\}`, 'g'), params[p]);
    });
  }

  return text;
};
