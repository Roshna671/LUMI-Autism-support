import io
import os
import hashlib

# Compatibility fix for ReportLab on Python 3.8 (where md5 does not take usedforsecurity keyword)
try:
    hashlib.md5(b"test", usedforsecurity=False)
except TypeError:
    _orig_md5 = hashlib.md5
    def _safe_md5(*args, **kwargs):
        kwargs.pop("usedforsecurity", None)
        return _orig_md5(*args, **kwargs)
    hashlib.md5 = _safe_md5

from typing import Dict, Any, List, Optional
from datetime import datetime, timedelta
from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, HRFlowable
)
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from sqlalchemy.orm import Session
from app.models.entities import ActivitySession, Child, Report

NON_CLINICAL_DISCLAIMER = (
    "NOTICE: This document is an activity engagement and developmental practice summary "
    "generated by LUMI for caregiver support. It is NOT a clinical evaluation, medical report, "
    "or diagnostic tool for Autism Spectrum Disorder or other conditions. Consult a qualified "
    "pediatrician, psychologist, or developmental specialist for clinical assessments."
)

class ReportService:
    @staticmethod
    def generate_daily_report(
        db: Session,
        child_id: str,
        target_date: Optional[str] = None
    ) -> Dict[str, Any]:
        child = db.query(Child).filter(Child.id == child_id).first()
        child_name = child.preferred_name if child else "Child"

        today_str = target_date or datetime.utcnow().strftime("%Y-%m-%d")
        
        # Query sessions from target date
        sessions = (
            db.query(ActivitySession)
            .filter(ActivitySession.child_id == child_id)
            .all()
        )
        
        # Filter for the day
        day_sessions = [
            s for s in sessions 
            if s.started_at and s.started_at.strftime("%Y-%m-%d") == today_str
        ]

        total_secs = sum(s.duration_seconds or 0 for s in day_sessions)
        total_duration_mins = round(total_secs / 60)
        activities_count = len(day_sessions)
        
        total_attempts = sum(s.attempts or 0 for s in day_sessions)
        total_successes = sum(s.successful_responses or 0 for s in day_sessions)
        total_prompts = sum(s.prompts_used or 0 for s in day_sessions)
        total_breaks = sum(s.breaks_taken or 0 for s in day_sessions)

        accuracy_rate = round((total_successes / total_attempts * 100), 1) if total_attempts > 0 else 0.0

        activity_summary = []
        for s in day_sessions:
            activity_summary.append({
                "activity_id": s.activity_id,
                "duration_minutes": round((s.duration_seconds or 0) / 60, 1),
                "attempts": s.attempts,
                "successes": s.successful_responses,
                "prompts": s.prompts_used,
                "status": s.completion_status,
                "difficulty": s.difficulty
            })

        # Recharts-ready trends
        trends = [
            {"name": "Accuracy %", "value": accuracy_rate},
            {"name": "Active Mins", "value": float(total_duration_mins)},
            {"name": "Prompts Needed", "value": float(total_prompts)},
            {"name": "Breaks Taken", "value": float(total_breaks)}
        ]

        # Suggestions
        suggestions = []
        if total_breaks > 2:
            suggestions.append("Keep tomorrow's sessions shorter (5-7 minutes) with calming sensory intervals.")
        elif accuracy_rate >= 85 and total_attempts >= 5:
            suggestions.append(f"{child_name} showed great confidence today! You can introduce gentle new challenges.")
        else:
            suggestions.append("Continue standard daily rhythm with praise and child-led pacing.")

        suggestions.append("Incorporate real-world emotion labeling during playtime or storybook reading.")

        missing_data = []
        if activities_count == 0:
            missing_data.append("No activity sessions were recorded for today.")

        report_data = {
            "id": f"rep-{child_id}-{today_str}",
            "child_id": child_id,
            "report_date": today_str,
            "report_type": "daily",
            "total_duration_minutes": total_duration_mins,
            "activities_completed_count": activities_count,
            "activity_summary": activity_summary,
            "measurable_outcomes": {
                "accuracy_percentage": accuracy_rate,
                "total_prompts": total_prompts,
                "total_breaks": total_breaks,
                "completion_rate": 100.0 if activities_count > 0 else 0.0
            },
            "trends": trends,
            "missing_data_indicators": missing_data,
            "suggestions_for_tomorrow": suggestions,
            "caregiver_notes": None,
            "pdf_download_url": f"/api/reports/child/{child_id}/daily/{today_str}/pdf",
            "non_clinical_disclaimer": NON_CLINICAL_DISCLAIMER
        }

        return report_data

    @staticmethod
    def generate_weekly_report(
        db: Session,
        child_id: str
    ) -> Dict[str, Any]:
        child = db.query(Child).filter(Child.id == child_id).first()
        child_name = child.preferred_name if child else "Child"

        today = datetime.utcnow()
        week_ago = today - timedelta(days=7)
        week_str = f"{week_ago.strftime('%b %d')} - {today.strftime('%b %d, %Y')}"

        sessions = (
            db.query(ActivitySession)
            .filter(ActivitySession.child_id == child_id)
            .filter(ActivitySession.started_at >= week_ago)
            .all()
        )

        total_sessions = len(sessions)
        total_active_minutes = round(sum(s.duration_seconds or 0 for s in sessions) / 60)

        # Build day-by-day Recharts series
        day_map = { (today - timedelta(days=i)).strftime("%a"): 0 for i in reversed(range(7)) }
        activity_freq: Dict[str, int] = {}

        for s in sessions:
            if s.started_at:
                d_key = s.started_at.strftime("%a")
                if d_key in day_map:
                    day_map[d_key] += round((s.duration_seconds or 0) / 60)
            act_id = s.activity_id or "general"
            activity_freq[act_id] = activity_freq.get(act_id, 0) + 1

        daily_durations = [{"name": day, "value": float(mins)} for day, mins in day_map.items()]

        top_activities = [
            {"activity_id": act, "sessions_count": count}
            for act, count in sorted(activity_freq.items(), key=lambda x: x[1], reverse=True)[:4]
        ]

        summary_text = (
            f"Over the past 7 days, {child_name} completed {total_sessions} sessions "
            f"totaling {total_active_minutes} active minutes. Consistent engagement in "
            f"emotion recognition and visual attention exercises was observed."
        )

        return {
            "child_id": child_id,
            "week_range": week_str,
            "total_sessions": total_sessions,
            "total_active_minutes": total_active_minutes,
            "daily_durations": daily_durations,
            "top_activities": top_activities,
            "progress_summary": summary_text,
            "non_clinical_disclaimer": NON_CLINICAL_DISCLAIMER
        }

    @staticmethod
    def generate_pdf(report_data: Dict[str, Any], child_profile: Dict[str, Any]) -> bytes:
        """
        Builds a crisp, professional ReportLab PDF summary document.
        """
        buffer = io.BytesIO()
        doc = SimpleDocTemplate(
            buffer,
            pagesize=letter,
            rightMargin=36,
            leftMargin=36,
            topMargin=36,
            bottomMargin=36
        )

        styles = getSampleStyleSheet()
        title_style = ParagraphStyle(
            "DocTitle",
            parent=styles["Heading1"],
            fontSize=18,
            leading=22,
            textColor=colors.HexColor("#1e1b4b"),
            spaceAfter=4
        )
        subtitle_style = ParagraphStyle(
            "DocSubTitle",
            parent=styles["Normal"],
            fontSize=10,
            leading=14,
            textColor=colors.HexColor("#6b7280"),
            spaceAfter=12
        )
        section_style = ParagraphStyle(
            "SectionHeading",
            parent=styles["Heading2"],
            fontSize=12,
            leading=16,
            textColor=colors.HexColor("#312e81"),
            spaceBefore=10,
            spaceAfter=6
        )
        body_style = ParagraphStyle(
            "DocBody",
            parent=styles["Normal"],
            fontSize=9,
            leading=13,
            textColor=colors.HexColor("#374151")
        )
        disclaimer_style = ParagraphStyle(
            "Disclaimer",
            parent=styles["Normal"],
            fontSize=8,
            leading=11,
            textColor=colors.HexColor("#991b1b")
        )

        elements = []

        # Title & Subtitle
        elements.append(Paragraph("<b>LUMI — Developmental Support & Activity Summary</b>", title_style))
        elements.append(Paragraph("Adaptive Early Childhood Learning Companion • Caregiver Progress Document", subtitle_style))
        elements.append(HRFlowable(width="100%", thickness=1.5, color=colors.HexColor("#6366f1"), spaceAfter=10))

        # Child and Report Metadata
        meta_data = [
            [
                Paragraph(f"<b>Child Name:</b> {child_profile.get('preferred_name', 'Child')}", body_style),
                Paragraph(f"<b>Report Date:</b> {report_data.get('report_date', 'N/A')}", body_style)
            ],
            [
                Paragraph(f"<b>Age:</b> {child_profile.get('age', 'N/A')} yrs", body_style),
                Paragraph(f"<b>Total Active Time:</b> {report_data.get('total_duration_minutes', 0)} mins", body_style)
            ],
            [
                Paragraph(f"<b>Communication:</b> {child_profile.get('communication_preferences', {}).get('style', 'Spoken / AAC')}", body_style),
                Paragraph(f"<b>Activities Completed:</b> {report_data.get('activities_completed_count', 0)}", body_style)
            ]
        ]
        meta_table = Table(meta_data, colWidths=[270, 270])
        meta_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor("#f8fafc")),
            ('PADDING', (0, 0), (-1, -1), 6),
            ('BOX', (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
            ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ]))
        elements.append(meta_table)
        elements.append(Spacer(1, 12))

        # Activity Breakdown Table
        elements.append(Paragraph("<b>Activity Engagement Breakdown</b>", section_style))
        act_summary = report_data.get("activity_summary", [])
        if act_summary:
            table_rows = [["Activity", "Duration", "Attempts", "Successes", "Prompts", "Status"]]
            for a in act_summary:
                table_rows.append([
                    str(a.get("activity_id", "")),
                    f"{a.get('duration_minutes', 0)}m",
                    str(a.get("attempts", 0)),
                    str(a.get("successes", 0)),
                    str(a.get("prompts", 0)),
                    str(a.get("status", "completed"))
                ])
            act_table = Table(table_rows, colWidths=[150, 75, 75, 75, 75, 90])
            act_table.setStyle(TableStyle([
                ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor("#e0e7ff")),
                ('TEXTCOLOR', (0, 0), (-1, 0), colors.HexColor("#1e1b4b")),
                ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
                ('FONTSIZE', (0, 0), (-1, -1), 8),
                ('PADDING', (0, 0), (-1, -1), 5),
                ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
                ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.HexColor("#f8fafc")]),
            ]))
            elements.append(act_table)
        else:
            elements.append(Paragraph("<i>No activities recorded for this date.</i>", body_style))

        elements.append(Spacer(1, 12))

        # Suggestions & Observations
        elements.append(Paragraph("<b>Caregiver Suggestions & Tomorrow's Pacing</b>", section_style))
        for tip in report_data.get("suggestions_for_tomorrow", []):
            elements.append(Paragraph(f"• {tip}", body_style))
            elements.append(Spacer(1, 3))

        elements.append(Spacer(1, 16))

        # Ethical Disclaimer Box
        disclaimer_table = Table([[Paragraph(f"<b>IMPORTANT ETHICAL & CLINICAL NOTICE:</b><br/>{NON_CLINICAL_DISCLAIMER}", disclaimer_style)]], colWidths=[540])
        disclaimer_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor("#fef2f2")),
            ('BOX', (0, 0), (-1, -1), 1, colors.HexColor("#f87171")),
            ('PADDING', (0, 0), (-1, -1), 8),
        ]))
        elements.append(disclaimer_table)

        doc.build(elements)
        buffer.seek(0)
        return buffer.getvalue()
